function fakeD1({ broken } = {}) {
  const calls = [];
  const statement = sql => ({
    bind() { return this; },
    all: async () => {
      calls.push(sql);
      if (broken) throw new Error("D1 is not listening");
      return { success: true, results: /^\s*SELECT 1/i.test(sql) ? [{ ok: 1 }] : [], meta: { changes: 0, last_row_id: 0 } };
    },
  });
  return { __calls: calls, prepare: statement, batch: async list => list.map(() => ({ success: true, results: [], meta: { changes: 0 } })) };
}

function fakeMedia(files) {
  const store = new Map(files);
  return {
    __store: store,
    head: async key => {
      const value = store.get(key);
      if (!value) return null;
      return { size: value.body.length, etag: value.etag || "FAKEETAG", uploaded: new Date(value.uploaded || "2026-10-01T00:00:00.000Z"), httpMetadata: { contentType: value.type } };
    },
    get: async (key, options) => {
      const value = store.get(key);
      if (!value) return null;
      const range = options && options.range;
      const body = range ? value.body.slice(range.offset, range.offset + range.length) : value.body;
      return { body, httpMetadata: { contentType: value.type } };
    },
    put: async () => {},
    delete: async () => {},
  };
}

/** A Durable Object host for the shipped RateLimiter class: one live instance per id, storage that
    survives a recycle, and every wire message the shim sent recorded for inspection. */
function fakeCounters(RateLimiter) {
  const saved = {};
  const recorded = [];
  const writes = [];
  let instance = null;
  let liveInstances = 0;
  const state = {
    storage: {
      get: async key => saved[key],
      put: async (key, value) => { saved[key] = JSON.parse(JSON.stringify(value)); },
    },
    waitUntil: promise => writes.push(Promise.resolve(promise)),
  };
  const stub = {
    fetch: async (input, init) => {
      const request = new Request(input, init);
      recorded.push({ url: request.url, method: request.method, type: request.headers.get("content-type"), body: await request.clone().json() });
      if (!instance) { instance = new RateLimiter(state); liveInstances++; }
      return instance.fetch(request);
    },
  };
  return {
    binding: { idFromName: name => `do:${name}`, get: () => stub },
    recorded,
    hits: key => (saved.buckets && saved.buckets[key] ? saved.buckets[key].hits : undefined),
    keys: () => Object.keys(saved.buckets || {}),
    snapshot: () => JSON.parse(JSON.stringify(saved.buckets || {})),
    recycle: () => { instance = null; },
    instances: () => liveInstances,
    settle: async () => { await Promise.allSettled(writes.splice(0)); },
  };
}

/* ------------------------------------------------------------------ *
 *  the entry, evaluated in the format the file is written in
 * ------------------------------------------------------------------ */
async function loadEntry() {
  /* one context for the whole graph: linked modules must share it, and using the real global means
     the app sees the same Request/Response/Date the Worker runtime would give it */
  const context = vm.createContext(globalThis);
  const cjsNamespace = filename => {
    const loaded = require(filename);
    const names = ["default", ...Object.keys(loaded)];
    return new vm.SyntheticModule(names, function () {
      for (const name of names) this.setExport(name, name === "default" ? loaded : loaded[name]);
    }, { context, identifier: `cjs:${filename}` });
  };
  const cache = new Map();
  const link = async (specifier, referencing, promiseResolve) => {
    if (!specifier.startsWith(".")) throw new Error(`worker.js should import nothing but relative paths, saw ${specifier}`);
    const filename = path.resolve(SRC, specifier);
    if (!cache.has(filename)) cache.set(filename, cjsNamespace(filename));
    /* Node 22+ wants the module returned; older linkers wanted promiseResolve() called */
    if (typeof promiseResolve === "function") promiseResolve(specifier);
    return cache.get(filename);
  };
  const identifier = path.join(SRC, "worker.js");
  const source = new vm.SourceTextModule(fs.readFileSync(identifier, "utf8"), {
    identifier, context, link,
  });
  await source.link(link);
  await source.evaluate();
  return source.namespace;
}

