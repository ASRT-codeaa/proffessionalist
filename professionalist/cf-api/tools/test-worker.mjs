const realLoad = Module._load;
Module._load = function (request, parent, isMain) {
  if (/port[\\/]/.test(request)) {
    const found = portStandIn(request);
    if (!found) throw new Error(`test-worker: no port stand-in for ${request}`);
    return found;
  }
  return realLoad.call(this, request, parent, isMain);
};

