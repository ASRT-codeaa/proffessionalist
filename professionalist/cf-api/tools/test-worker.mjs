/* a block of source, comment- and indentation-normalised, for "transcribed verbatim" claims */
const block = (src, start, stop, label) => {
  const from = src.indexOf(start);
  if (from < 0) throw new Error(`${label}: could not find ${JSON.stringify(start)}`);
  const to = src.indexOf(stop, from);
  if (to < 0) throw new Error(`${label}: could not find ${JSON.stringify(stop)} after it`);
  return src.slice(from, to + stop.length).split("\n").map(line => line.trim()).filter(Boolean).join("\n");
};

