/* Verify cf-api/src/worker.js and cf-api/src/api.js together, the way the runtime runs them: the
   real ESM entry, the real transcribed server.js mounting, the real limit/upload/db shims and the
   real RateLimiter Durable Object class, against fakes for exactly the three bindings (D1, R2, DO
   storage) and nothing else.

   Three things this harness has to do that the other harnesses here do not:
     - worker.js is ESM while cf-api/package.json says "type": "commonjs", so a plain `import()` of
       it dies on its first `import` line.  vm.SourceTextModule evaluates it with the module format
       the file actually uses, which is the format wrangler's esbuild sees; the re-exec below adds
       the flag that costs.
     - cf-api/port/ is generated by another engineer and may not exist.  api.js requires it lazily
       (that is the entire point of that design), so in-memory stand-ins are substituted through
       Module._load instead of writing files into a tree this harness does not own.
     - every expected byte is taken out of /workspaces/app-mirror/app/server.js at run time and some
       whole blocks are compared textually against cf-api/src/api.js, so a message, a status→code
       mapping or a limiter option that drifts from the mirror fails here rather than passing on a
       transcription of the same mistake.

   Limits are the one part of the shared app that cannot be re-configured per case (the limiter
   option objects are built once, when the app is assembled, exactly as on the VPS), so the single
   env below uses IP_RATE_LIMIT=4 / AUTH_RATE_LIMIT=2 / USER_RATE_LIMIT=400: every ordinary request
   gets its own X-Forwarded-For value so no bucket accumulates, and the two clamp cases reuse one
   address on purpose.
     node cf-api/tools/test-worker.mjs */
